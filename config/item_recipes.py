def get_upgrades_map():
    """
    动态计算反向'可合成装备'树
    输入原件 -> 输出可升级合成的方向列表
    """
    upgrades_map = {}
    for parent, children in COMPONENTS_MAP.items():
        for child in children:
            if child not in upgrades_map:
                upgrades_map[child] = []
            if parent not in upgrades_map[child]:
                upgrades_map[child].append(parent)
    return upgrades_map
