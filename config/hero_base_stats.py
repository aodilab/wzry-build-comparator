def get_hero_base_stats(ename, cname, role_str="战士"):
    """
    获取指定英雄的基础属性面板（包含1级基础、15级成长、物攻、物抗、魔抗、移速）
    """
    eid = int(ename) if str(ename).isdigit() else 0
    if eid in HERO_SPECIAL_STATS:
        return HERO_SPECIAL_STATS[eid]

    # 根据主职业取基准模板
    main_role = role_str.split("/")[0] if role_str else "战士"
    tmpl = ROLE_BASE_TEMPLATES.get(main_role, ROLE_BASE_TEMPLATES["战士"])

    return {
        "cname": cname,
        "hp": tmpl["hp"],
        "atk": tmpl["atk"],
        "pdef": tmpl["pdef"],
        "mdef": tmpl["mdef"],
        "speed": tmpl["speed"],
        "aspeed": tmpl["aspeed"]
    }
